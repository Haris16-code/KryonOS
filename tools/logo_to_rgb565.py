#!/usr/bin/env python3
"""
KryonOS Sponsor Logo to RGB565 PROGMEM Converter
------------------------------------------------
Usage:
    python tools/logo_to_rgb565.py <input_image.png> <ARRAY_NAME> [--width 166] [--bg 0x10A2] [--out output.h]

Description:
    Resizes a PNG/JPG logo preserving aspect ratio, alpha-blends transparent pixels
    against the target card background color (default: 0x10A2), and outputs a
    C/C++ PROGMEM uint16_t RGB565 array ready for src/Settings/SponsorAssets.h.
"""

import argparse
import sys
from PIL import Image


def rgb565_to_rgb888(c565):
    r5 = (c565 >> 11) & 0x1F
    g6 = (c565 >> 5) & 0x3F
    b5 = c565 & 0x1F
    r = (r5 * 255 + 15) // 31
    g = (g6 * 255 + 31) // 63
    b = (b5 * 255 + 15) // 31
    return (r, g, b)


def rgb888_to_rgb565(r, g, b):
    return ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)


def convert_logo(image_path, array_name, target_w=166, bg_rgb565=0x10A2):
    im = Image.open(image_path).convert("RGBA")
    orig_w, orig_h = im.size
    target_h = max(1, int(round(orig_h * (target_w / float(orig_w)))))

    im_resized = im.resize((target_w, target_h), Image.Resampling.LANCZOS)
    bg_r, bg_g, bg_b = rgb565_to_rgb888(bg_rgb565)

    pixels_565 = []
    for y in range(target_h):
        for x in range(target_w):
            r, g, b, a = im_resized.getpixel((x, y))
            alpha = a / 255.0
            out_r = int(round(r * alpha + bg_r * (1.0 - alpha)))
            out_g = int(round(g * alpha + bg_g * (1.0 - alpha)))
            out_b = int(round(b * alpha + bg_b * (1.0 - alpha)))
            out_r = max(0, min(255, out_r))
            out_g = max(0, min(255, out_g))
            out_b = max(0, min(255, out_b))
            pixels_565.append(rgb888_to_rgb565(out_r, out_g, out_b))

    lines = []
    lines.append(f"// Generated by tools/logo_to_rgb565.py from {image_path}")
    lines.append(f"// Dimensions: {target_w}x{target_h} pixels ({len(pixels_565) * 2} bytes)")
    lines.append(f"#define {array_name}_WIDTH  {target_w}")
    lines.append(f"#define {array_name}_HEIGHT {target_h}")
    lines.append(f"static const uint16_t {array_name}[{len(pixels_565)}] PROGMEM = {{")

    row_chunk = 12
    for i in range(0, len(pixels_565), row_chunk):
        chunk = pixels_565[i:i + row_chunk]
        hex_vals = ", ".join(f"0x{val:04X}" for val in chunk)
        comma = "," if (i + row_chunk < len(pixels_565)) else ""
        lines.append(f"    {hex_vals}{comma}")

    lines.append("};")
    return "\n".join(lines), target_w, target_h


def main():
    parser = argparse.ArgumentParser(description="Convert Sponsor Logo PNG/JPG to RGB565 PROGMEM array.")
    parser.add_argument("image", help="Path to input PNG/JPG image")
    parser.add_argument("name", help="C identifier name for the array (e.g. AMERIDROID_LOGO_RGB565)")
    parser.add_argument("--width", type=int, default=166, help="Target width in pixels (default: 166)")
    parser.add_argument("--bg", type=lambda x: int(x, 0), default=0x10A2, help="Background RGB565 hex color (default: 0x10A2)")
    parser.add_argument("--out", default=None, help="Optional output file path")
    args = parser.parse_args()

    code, w, h = convert_logo(args.image, args.name, args.width, args.bg)
    if args.out:
        with open(args.out, "w", encoding="utf-8") as f:
            f.write(code + "\n")
        print(f"Saved {args.name} ({w}x{h}) to {args.out}")
    else:
        print(code)


if __name__ == "__main__":
    main()

